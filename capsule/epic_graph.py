"""The epic dependency graph as a static Mermaid page (VIS-07, decision row 379 item 46).

Read-only over one board: every card on a declared epic branch is a node, grouped into one
subgraph per epic; `task_links` are the edges (a card outside every epic joins only when a link
touches an epic card). Regenerated by `python3 -m capsule.epic_graph --board B` (nightly, host
schedule); output is an `.html` page plus the raw `.mmd`, never raw ids, safe to open offline
except for the pinned Mermaid script."""
import argparse
import html
import json
import re
import sys
from pathlib import Path

from capsule import config, db, paths, safe_write

TITLE_CAP = 60
CLASSES = {"done": "done", "archived": "done", "running": "running", "review": "running",
           "blocked": "blocked", "parked": "blocked", "triage": "blocked"}
STYLES = ("classDef done fill:#d4edda,stroke:#2e7d32",
          "classDef running fill:#fff3cd,stroke:#b8860b",
          "classDef blocked fill:#f8d7da,stroke:#b71c1c",
          "classDef open fill:#e8eef7,stroke:#456")
_BAD = re.compile(r'[\x00-\x1f"\[\]{}()<>|`#%&;\\]')


def _label(text):
    t = _BAD.sub(" ", str(text or ""))
    t = re.sub(r"\s+", " ", t).strip() or "card"
    return t if len(t) <= TITLE_CAP else t[:TITLE_CAP - 1].rstrip() + "..."


def render(conn, branches):
    """Mermaid flowchart text for `branches` (epic branch names) on `conn`."""
    marks = ",".join("?" * len(branches)) or "''"
    cols = "SELECT id, title, short_name, status, branch_name FROM tasks"
    epic_rows = conn.execute(
        f"{cols} WHERE branch_name IN ({marks}) ORDER BY COALESCE(number, 0), id",
        list(branches)).fetchall()
    nodes = {r["id"]: r for r in epic_rows}
    every = conn.execute("SELECT parent_id, child_id FROM task_links ORDER BY 1, 2")
    links = [(p, c) for p, c in every if p in nodes or c in nodes]
    extra = {x for pair in links for x in pair} - set(nodes)
    for r in conn.execute(f"{cols} ORDER BY id"):
        if r["id"] in extra:
            nodes[r["id"]] = r
    ref = {tid: f"n{i}" for i, tid in enumerate(nodes)}

    def node(tid):
        r = nodes[tid]
        cls = CLASSES.get(r["status"], "open")
        return f'{ref[tid]}["{_label(r["short_name"] or r["title"])}"]:::{cls}'

    lines = ["flowchart LR"]
    for i, branch in enumerate(branches):
        lines.append(f'  subgraph e{i}["{_label(branch)}"]')
        lines += [f"    {node(t)}" for t, r in nodes.items() if r["branch_name"] == branch]
        lines.append("  end")
    outside = [t for t, r in nodes.items() if r["branch_name"] not in branches]
    if outside:
        lines.append('  subgraph other["outside the epics"]')
        lines += [f"    {node(t)}" for t in outside]
        lines.append("  end")
    lines += [f"  {ref[p]} --> {ref[c]}" for p, c in links]
    lines += [f"  {s}" for s in STYLES]
    return "\n".join(lines) + "\n"


def main(argv=None):
    """Write `epic-graph.mmd` + `epic-graph.html` for one board (read-only); print the paths."""
    ap = argparse.ArgumentParser(prog="python3 -m capsule.epic_graph")
    ap.add_argument("--board", required=True)
    ap.add_argument("--home")
    ap.add_argument("--out", help="default: <home>/pages/<board>")
    a = ap.parse_args(argv)
    home = paths.home(a.home)
    cfg = json.loads(paths.resolve_config(home, a.board).read_text())
    conn = db.connect_ro_tolerant(paths.board_db(a.board, home))
    try:
        mmd = render(conn, config.epic_branches_from_list(cfg.get("epics")))
    finally:
        conn.close()
    title = html.escape(a.board)
    esm = "https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.esm.min.mjs"
    page = ('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            f"<title>Epic dependency graph - {title}</title></head>\n<body>\n"
            f"<h1>Epic dependency graph: {title}</h1>\n"
            f'<pre class="mermaid">\n{html.escape(mmd)}</pre>\n'
            f'<script type="module">import mermaid from "{esm}"; '
            "mermaid.initialize({startOnLoad: true});</script>\n</body></html>\n")
    base = Path(a.out) if a.out else home / "pages" / a.board
    root = Path(a.out) if a.out else home
    for name, data in (("epic-graph.mmd", mmd), ("epic-graph.html", page)):
        safe_write.atomic_write(root, base / name, data, create_dirs=True)
        print(base / name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
