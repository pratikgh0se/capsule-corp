"""Row 470's exporter (capsule/metrics.py): reads the `capsule unblocked --json` detector's
cached JSON (the real shape, sibling branch capsule/unblocked sha c46cae4 - see
`capsule/tests/fixtures/unblocked/sample.json`, generated by running that branch's own
`render_json` against a handful of constructed items) and combines it with capsule's own dispatch
clock to build the three metrics the dead-man alert (rules.yaml's `unowned-work-idle`) reads."""
import json
import os
import tempfile
import unittest
import unittest.mock
from pathlib import Path

from capsule import metrics, paths

SAMPLE = paths.REPO / "capsule" / "tests" / "fixtures" / "unblocked" / "sample.json"


class RealFixture(unittest.TestCase):
    """The detector's actual output shape - no `last_dispatch_ts` or any other timestamp field
    anywhere in it (row 470 follow-up: the original assumption of a detector-supplied timestamp
    was wrong; capsule tracks that clock itself, see `Tick._record_dispatch`)."""

    def test_sample_has_the_real_shape_and_no_timestamp_field(self):
        doc = json.loads(SAMPLE.read_text())
        self.assertEqual(set(doc), {"items", "unblocked", "unowned"})
        self.assertIsInstance(doc["items"], list)
        for item in doc["items"]:
            self.assertEqual(set(item), {"item", "source", "state", "blocker", "owner", "age_s"})

    def test_reading_the_real_fixture_yields_the_two_detector_metrics_only(self):
        # max_age=None: this is a checked-in fixture, not a live cache file - its mtime tracks
        # git, not the detector's own freshness, so staleness (I1) does not apply to it.
        self.assertEqual(metrics.metrics_payload(metrics.read_cache(SAMPLE, max_age=None)),
                         {"capsule_unblocked_total": 3, "capsule_unowned_total": 2})

    def test_reading_the_real_fixture_plus_a_dispatch_clock_yields_all_three(self):
        self.assertEqual(metrics.metrics_payload(metrics.read_cache(SAMPLE, max_age=None), last_dispatch_ts=1000),
                         {"capsule_unblocked_total": 3, "capsule_unowned_total": 2,
                          "capsule_last_dispatch_timestamp": 1000})


class ReadCache(unittest.TestCase):
    def test_missing_file_is_none(self):
        self.assertIsNone(metrics.read_cache(Path(tempfile.mkdtemp()) / "no-such-file.json"))

    def test_invalid_json_is_none(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("not json{{{")
        self.assertIsNone(metrics.read_cache(p))

    def test_json_that_is_not_an_object_is_none(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("[1, 2, 3]")
        self.assertIsNone(metrics.read_cache(p))

    def test_valid_object_round_trips(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        doc = {"items": [], "unblocked": 3, "unowned": 2}
        p.write_text(json.dumps(doc))
        self.assertEqual(metrics.read_cache(p), doc)

    def test_a_stale_file_is_none_even_though_it_parses_fine(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text(json.dumps({"unblocked": 3, "unowned": 2}))
        stale_mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS - 1
        os.utime(p, (stale_mtime, stale_mtime))
        self.assertIsNone(metrics.read_cache(p, now=1_000_000))

    def test_a_fresh_file_within_max_age_still_reads(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        doc = {"unblocked": 3, "unowned": 2}
        p.write_text(json.dumps(doc))
        fresh_mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS + 1
        os.utime(p, (fresh_mtime, fresh_mtime))
        self.assertEqual(metrics.read_cache(p, now=1_000_000), doc)

    def test_exactly_max_age_old_is_not_yet_stale(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        doc = {"unblocked": 1, "unowned": 1}
        p.write_text(json.dumps(doc))
        mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS
        os.utime(p, (mtime, mtime))
        self.assertEqual(metrics.read_cache(p, now=1_000_000), doc)


class CacheIsStale(unittest.TestCase):
    def test_missing_file_is_not_stale(self):
        # missing is its own "no data" case, not "stale" - read_cache already returns None for
        # it through the ordinary path, this must never ALSO print a stale transition for it.
        p = Path(tempfile.mkdtemp()) / "no-such-file.json"
        self.assertFalse(metrics.cache_is_stale(p, now=1_000_000))

    def test_old_mtime_is_stale(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("{}")
        mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS - 1
        os.utime(p, (mtime, mtime))
        self.assertTrue(metrics.cache_is_stale(p, now=1_000_000))

    def test_recent_mtime_is_not_stale(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("{}")
        mtime = 1_000_000 - 5
        os.utime(p, (mtime, mtime))
        self.assertFalse(metrics.cache_is_stale(p, now=1_000_000))

    def test_a_corrupt_but_fresh_file_is_not_stale(self):
        # row 472 re-review (R2): "stale" and "corrupt" are different reasons for "no data" -
        # cache_is_stale is specifically about mtime age, never about parse failure.
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("{{{not json")
        os.utime(p, (1_000_000, 1_000_000))
        self.assertFalse(metrics.cache_is_stale(p, now=1_000_000))


class CacheState(unittest.TestCase):
    """Row 472 re-review (R2): `cache_state` is the single source of truth for all four states
    (`metrics.CACHE_STATES`) - `read_cache`, `cache_is_stale` and `Tick._check_cache_staleness`
    all build on it, so each is named and testable on its own instead of one bare boolean that
    only ever meant "stale"."""

    def test_missing_file_is_missing(self):
        p = Path(tempfile.mkdtemp()) / "no-such-file.json"
        self.assertEqual(metrics.cache_state(p, now=1_000_000), "missing")

    def test_old_mtime_is_stale(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("{}")
        mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS - 1
        os.utime(p, (mtime, mtime))
        self.assertEqual(metrics.cache_state(p, now=1_000_000), "stale")

    def test_invalid_json_but_fresh_mtime_is_corrupt(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("{{{not valid json")
        os.utime(p, (1_000_000, 1_000_000))
        self.assertEqual(metrics.cache_state(p, now=1_000_000), "corrupt")

    def test_a_json_array_is_corrupt_not_fresh(self):
        # valid JSON, but not an object - "corrupt" for this module's purposes, same as garbage.
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("[1, 2, 3]")
        os.utime(p, (1_000_000, 1_000_000))
        self.assertEqual(metrics.cache_state(p, now=1_000_000), "corrupt")

    def test_fresh_valid_object_is_fresh(self):
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text(json.dumps({"unblocked": 1, "unowned": 1}))
        os.utime(p, (1_000_000, 1_000_000))
        self.assertEqual(metrics.cache_state(p, now=1_000_000), "fresh")

    def test_a_stale_but_otherwise_corrupt_file_is_stale_first(self):
        # staleness is checked from the mtime alone, before the content is even read - a file that
        # is BOTH old and garbage is "stale" (age wins - the same information a hook restart would
        # give you), not "corrupt".
        p = Path(tempfile.mkdtemp()) / "unblocked.json"
        p.write_text("{{{not valid json")
        mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS - 1
        os.utime(p, (mtime, mtime))
        self.assertEqual(metrics.cache_state(p, now=1_000_000), "stale")


class MetricsPayload(unittest.TestCase):
    def test_full_doc_and_dispatch_ts_emit_all_three_metric_names(self):
        doc = {"items": [], "unblocked": 3, "unowned": 2}
        self.assertEqual(metrics.metrics_payload(doc, last_dispatch_ts=1758943200), {
            "capsule_unblocked_total": 3, "capsule_unowned_total": 2,
            "capsule_last_dispatch_timestamp": 1758943200,
        })

    def test_partial_doc_emits_only_the_fields_present(self):
        self.assertEqual(metrics.metrics_payload({"unowned": 5}), {"capsule_unowned_total": 5})

    def test_no_dispatch_ts_is_not_a_fabricated_zero(self):
        self.assertEqual(metrics.metrics_payload({"unblocked": 1, "unowned": 0}),
                         {"capsule_unblocked_total": 1, "capsule_unowned_total": 0})

    def test_missing_doc_and_no_dispatch_ts_is_empty(self):
        self.assertEqual(metrics.metrics_payload(None), {})
        self.assertEqual(metrics.metrics_payload({}), {})

    def test_dispatch_ts_alone_with_no_doc_still_emits(self):
        self.assertEqual(metrics.metrics_payload(None, last_dispatch_ts=500),
                         {"capsule_last_dispatch_timestamp": 500})

    def test_non_numeric_field_is_dropped_not_raised(self):
        self.assertEqual(metrics.metrics_payload({"unowned": "two", "unblocked": 1}),
                         {"capsule_unblocked_total": 1})

    def test_bool_is_not_numeric(self):
        # bool is an int subclass in Python - a stray `true` must never become metric `1`.
        self.assertEqual(metrics.metrics_payload({"unowned": True}), {})
        self.assertEqual(metrics.metrics_payload({}, last_dispatch_ts=True), {})


class Export(unittest.TestCase):
    def setUp(self):
        self.path = Path(tempfile.mkdtemp()) / "unblocked.json"
        self.calls = []

    def fake_log(self, kind, source, text, *, board=None, payload=None):
        self.calls.append({"kind": kind, "source": source, "text": text, "board": board, "payload": payload})

    def test_missing_cache_and_no_dispatch_ts_exports_nothing(self):
        self.assertFalse(metrics.export(self.fake_log, path=self.path))
        self.assertEqual(self.calls, [])

    def test_full_cache_plus_dispatch_ts_exports_one_event_with_all_three_metrics(self):
        self.path.write_text(json.dumps({"items": [], "unblocked": 4, "unowned": 1}))
        self.assertTrue(metrics.export(self.fake_log, path=self.path, last_dispatch_ts=1000))
        self.assertEqual(len(self.calls), 1)
        call = self.calls[0]
        self.assertEqual(call["kind"], "capsule_unblocked")
        self.assertEqual(call["payload"], {"capsule_unblocked_total": 4, "capsule_unowned_total": 1,
                                           "capsule_last_dispatch_timestamp": 1000})

    def test_dispatch_ts_alone_with_a_missing_cache_still_exports(self):
        self.assertTrue(metrics.export(self.fake_log, path=self.path, last_dispatch_ts=42))
        self.assertEqual(self.calls[0]["payload"], {"capsule_last_dispatch_timestamp": 42})

    def test_cache_with_no_recognised_fields_and_no_dispatch_ts_exports_nothing(self):
        self.path.write_text(json.dumps({"items": []}))
        self.assertFalse(metrics.export(self.fake_log, path=self.path))
        self.assertEqual(self.calls, [])

    def test_invalid_json_exports_nothing_and_never_raises(self):
        self.path.write_text("{{{not json")
        self.assertFalse(metrics.export(self.fake_log, path=self.path))

    def test_board_is_passed_through_to_log(self):
        self.path.write_text(json.dumps({"unblocked": 1, "unowned": 1}))
        metrics.export(self.fake_log, path=self.path, board="capsule-corp")
        self.assertEqual(self.calls[0]["board"], "capsule-corp")

    def test_a_stale_cache_exports_nothing(self):
        self.path.write_text(json.dumps({"unblocked": 4, "unowned": 1}))
        stale_mtime = 1_000_000 - metrics.CACHE_MAX_AGE_SECONDS - 1
        os.utime(self.path, (stale_mtime, stale_mtime))
        self.assertFalse(metrics.export(self.fake_log, path=self.path, now=1_000_000))
        self.assertEqual(self.calls, [])


class RefreshCache(unittest.TestCase):
    """t_742be58f (option A): the tick recomputes a stale cache itself, through the real detector
    (capsule/unblocked.py), so the unowned count is on every pass and a missing one is a signal."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.path = self.tmp / "unblocked.json"
        self.homes = {"capsule_home": self.tmp / "capsule"}
        self.calls = []
        metrics._refresh_failing = False

    def fake_log(self, kind, source, text, *, board=None, payload=None):
        self.calls.append(payload)

    def make_stale(self):
        self.path.write_text(json.dumps({"items": [], "unblocked": 9, "unowned": 9}))
        os.utime(self.path, (1, 1))

    def test_stale_cache_is_rewritten_by_the_real_detector(self):
        self.make_stale()
        self.assertTrue(metrics._refresh_cache(self.path, detect_args=self.homes))
        doc = json.loads(self.path.read_text())
        self.assertEqual(set(doc), {"items", "unblocked", "unowned"})
        self.assertNotEqual(doc["unowned"], 9)
        self.assertEqual(metrics.cache_state(self.path), "fresh")

    def test_no_injected_homes_resolves_them_from_the_environment(self):
        """The live tick passes no detect/detect_args: `detect()` must resolve its own homes."""
        env = {"CAPSULE_HOME": str(self.homes["capsule_home"])}
        with unittest.mock.patch.dict(os.environ, env):
            self.assertTrue(metrics._refresh_cache(self.path))
        self.assertEqual(metrics.cache_state(self.path), "fresh")
        self.assertFalse(metrics._refresh_failing)

    def test_missing_cache_is_created(self):
        self.assertTrue(metrics._refresh_cache(self.path, detect_args=self.homes))
        self.assertEqual(metrics.cache_state(self.path), "fresh")

    def test_fresh_cache_is_left_alone(self):
        self.path.write_text(json.dumps({"items": [], "unblocked": 9, "unowned": 9}))
        self.assertFalse(metrics._refresh_cache(self.path, detect_args=self.homes))
        self.assertEqual(json.loads(self.path.read_text())["unowned"], 9)

    def test_detector_error_is_swallowed_and_ships_no_unowned_metric(self):
        self.make_stale()
        def boom(**_):
            raise RuntimeError("detector down")
        self.assertFalse(metrics._refresh_cache(self.path, detect=boom))
        self.assertFalse(metrics.export(self.fake_log, path=self.path, refresh=True,
                                        detect=boom))
        self.assertEqual(json.loads(self.path.read_text())["unowned"], 9)

    def test_export_with_refresh_ships_the_unowned_count_from_a_stale_cache(self):
        self.make_stale()
        self.assertTrue(metrics.export(self.fake_log, path=self.path, refresh=True,
                                       detect_args=self.homes, last_dispatch_ts=5))
        self.assertIn("capsule_unowned_total", self.calls[0])
        self.assertNotEqual(self.calls[0]["capsule_unowned_total"], 9)

    def test_export_without_refresh_keeps_the_old_behaviour(self):
        self.make_stale()
        self.assertFalse(metrics.export(self.fake_log, path=self.path))

    def leftovers(self):
        return [p.name for p in self.tmp.iterdir() if p.name.startswith("unblocked.json.")]

    def test_no_tmp_file_is_left_behind_on_success_or_failure(self):
        self.make_stale()
        metrics._refresh_cache(self.path, detect_args=self.homes)
        self.assertEqual(self.leftovers(), [])
        self.make_stale()
        def boom(**_):
            raise RuntimeError("down")
        metrics._refresh_cache(self.path, detect=boom)
        self.assertEqual(self.leftovers(), [])

    def test_tmp_name_is_per_process_not_the_hooks_literal(self):
        self.make_stale()
        seen = []
        real_replace = os.replace
        def spy(src, dst):
            seen.append(Path(src).name)
            return real_replace(src, dst)
        os.replace = spy
        try:
            metrics._refresh_cache(self.path, detect_args=self.homes)
        finally:
            os.replace = real_replace
        self.assertEqual(len(seen), 1)
        self.assertNotEqual(seen[0], "unblocked.json.tmp")
        self.assertIn(str(os.getpid()), seen[0])

    def test_a_broken_detector_logs_once_per_outage_and_again_after_recovery(self):
        import contextlib
        import io
        def boom(**_):
            raise RuntimeError("down")
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            for _ in range(3):
                self.make_stale()
                metrics._refresh_cache(self.path, detect=boom)
        self.assertEqual(err.getvalue().count("refresh failed"), 1)
        self.make_stale()
        self.assertTrue(metrics._refresh_cache(self.path, detect_args=self.homes))
        err2 = io.StringIO()
        with contextlib.redirect_stderr(err2):
            self.make_stale()
            metrics._refresh_cache(self.path, detect=boom)
        self.assertEqual(err2.getvalue().count("refresh failed"), 1)

    def test_count_missing_window_outlasts_one_contract_command_by_five_minutes(self):
        from capsule import tick
        longest = max(tick.CONTRACT_TIMEOUT, 1200)    # 1200: the limit this window was sized for
        self.assertGreaterEqual(metrics.COUNT_MISSING_SECONDS, longest + 300)


