class RuleTypeSafety(unittest.TestCase):
    """Row 472 re-review (R1, HIGH): `events.ts` is `timestamptz`
    (observability/postgres/init.sql) - no rule's SQL may compare it against a bare numeric
    expression (`extract(epoch from now()) - N`, or any other numeric literal), which Postgres
    rejects outright at evaluation time ("operator does not exist: timestamp with time zone >
    numeric"). This exact mistake shipped in `unowned-work-idle` and passed every string-shape
    test that existed on it (a substring/regex check on the YAML text, never on whether Postgres
    itself accepts the SQL) - this test statically rejects the pattern across EVERY rule, not just
    this one, so it can never regress unnoticed again. `tests/test_alert_rules_pg.sh` is this
    test's second oracle: it runs every rule's rawSql against a real, throwaway Postgres loaded
    with the real schema (skips when docker is unavailable; this test runs unconditionally,
    docker or not)."""

    NUMERIC_TS_COMPARISON = re.compile(
        r"\bts\s*(?:<=|>=|<|>)\s*(?:extract\s*\(\s*epoch|\d)", re.IGNORECASE)

    def test_no_rule_compares_ts_against_a_numeric_expression(self):
        offenders = []
        for uid in _all_rule_uids():
            for sql in _raw_sql_texts(_rule_block(uid)):
                if self.NUMERIC_TS_COMPARISON.search(sql):
                    offenders.append((uid, sql.strip()[:200]))
        self.assertEqual(offenders, [])

    def test_the_fixed_rule_uses_the_interval_idiom_every_other_rule_already_uses(self):
        # the positive half of the check above: not just "no numeric comparison", but "uses the
        # SAME timestamptz-vs-timestamptz idiom `job-failed`/`backup-partial`/`card-stuck` already
        # use", so a future edit can copy this rule as a template without reintroducing the bug.
        sql = _raw_sql_texts(_rule_block("unowned-work-idle"))[0]
        # the window is the tick's own Korin hold (metrics.COUNT_MISSING_SECONDS), so a change to
        # either side without the other fails here
        self.assertIn(f"ts > now() - interval '{metrics.COUNT_MISSING_SECONDS // 60} minutes'", sql)
        # t_742be58f: the rule pages on detector silence only: the tick is alive (tick_health,
        # a dead tick is capsule-tick-deadman's page, no double page) and no count has arrived;
        # board='test' rows are never read.
        self.assertIn("kind='tick_health'", sql)
        self.assertEqual(sql.count("board <> 'test'"), 1)    # counts join on board
        # a NULL board and an unwatched leaked board never fire, as capsule-tick-deadman
        self.assertIn("board is not null", sql)
        self.assertIn("payload->>'watch'", sql)
        # t_86fc8bec: per board (no single newest row across boards) and pause-aware
        self.assertIn("distinct on (board)", sql)
        self.assertIn("u.board = h.board", sql)
        self.assertIn("payload->>'paused'", sql)
        self.assertNotIn("limit 1", sql)
        self.assertIn("payload->>'capsule_unowned_total' is not null", sql)
        self.assertNotIn("capsule_last_dispatch_timestamp", sql)
        self.assertNotIn("> 1800", sql)


class RuleShape(unittest.TestCase):
    """The rule itself: what row 470 asked for, pinned so a future edit that quietly drops the
    dead-man shape (e.g. losing the staleness half of the condition) is caught."""

    def setUp(self):
        self.block = _rule_block("unowned-work-idle")

    def test_page_severity_and_one_evaluation_of_grace(self):
        # row 472 (I7): the real 30-minute wait is the `> 1800` staleness half of the condition
        # itself (test_condition_reads_the_capsule_unblocked_event_row below); `for:` is one
        # evaluation of grace against a single flaky sample, not a second 30-minute wait stacked
        # on top - that used to make this a 60-minute alert.
        self.assertIn("severity: notice", self.block)   # row 623
        self.assertIn("for: 1m", self.block)
        self.assertIn("title: Unowned-work count missing", self.block)

    def test_runbook_points_at_a_shipped_page_heading(self):
        # row 472 (I5): derive the anchor from the real heading text, on a page that ships.
        path, anchor = re.search(r"runbook: (\S+\.md)#(\S+)", self.block).groups()
        self.assertNotIn("RUNBOOK", path)
        text = (paths.REPO / path).read_text()
        headings = re.findall(r"^#{2,4} (.+)$", text, re.MULTILINE)
        self.assertIn(anchor, [_heading_slug(h) for h in headings])
        section = text.split("## Alert rules", 1)[1].split("\n## ", 1)[0].lower()
        for title in re.findall(r"(?m)^        title: (.+)$", RULES.read_text()):
            self.assertIn(title.lower().replace(" %", " percent"), section, title)

    def test_condition_reads_the_capsule_unblocked_event_row(self):
        sql = _raw_sql_texts(self.block)[0]
        self.assertIn(f"kind='{metrics.EVENT_KIND}'", sql)
        self.assertIn(f"payload->>'{metrics.METRIC_NAMES['unowned']}' is not null", sql)

    def test_condition_bounds_ts_so_a_stopped_tick_is_no_data_not_frozen_data(self):
        # row 472 (I1): the Grafana side needs the same freshness guard the tick side got -
        # without a `ts` bound, a tick that stopped exporting entirely would leave the LATEST row
        # forever "current" as far as this query is concerned. Row 472 re-review (R1): `events.ts`
        # is `timestamptz` (observability/postgres/init.sql) - the bound has to compare it against
        # another timestamptz (`now() - interval '...'`), the same idiom every other rule here
        # already uses (e.g. `job-failed`'s `ts>now()-interval '15 minutes'`), never against a
        # numeric epoch value (`extract(epoch from now()) - N`), which Postgres rejects outright
        # ("operator does not exist: timestamp with time zone > numeric").
        sql = _raw_sql_texts(self.block)[0]
        self.assertRegex(sql, r"ts\s*>\s*now\(\)\s*-\s*interval\s*'\d+ minutes'")

    def test_datasource_is_the_same_ops_pg_every_other_rule_reads(self):
        self.assertIn("datasourceUid: ops-pg", self.block)

    @private_only
    def test_rule_uid_matches_the_tick_side_alert_key(self):
        # capsule/metrics.py's ALERT_KEY ("unowned_work_idle") is the fingerprint root_key
        # incidents.record_alert_firing opens on a repeat - the rule's own uid is its
        # hyphenated spelling, so a rename on either side is caught here, not only at runtime.
        self.assertEqual(metrics.ALERT_KEY.replace("_", "-"), "unowned-work-idle")
        self.assertIn(metrics.ALERT_KEY, (paths.REPO / "docs" / "RUNBOOK.md").read_text())


class PolicyRendererGolden(unittest.TestCase):
    """The routing half: unchanged render_alert_policy.py output, regenerated by its documented
    command, still sends `severity: page` (my rule's own label) to `capsule-slack-alerts`."""

    def test_render_alert_policy_matches_the_checked_in_golden(self):
        rendered = _render(POLICY_TEMPLATE)
        self.assertEqual(rendered, GOLDEN_SLACK1.read_text())

    def test_render_alert_policy_via_subprocess_matches_too(self):
        # the exact documented invocation (tests/test_deploy.sh), run as a subprocess rather than
        # imported, so a change to main()/argv handling is covered as well as render() itself.
        out = subprocess.run([sys.executable, str(RENDER_SCRIPT), str(POLICY_TEMPLATE)],
                             capture_output=True, text=True, check=True).stdout
        self.assertEqual(out, GOLDEN_SLACK1.read_text())

    def test_the_golden_routes_page_severity_to_slack_alerts_and_has_no_telegram_d133(self):
        # D133 (2026-10-30): the Telegram catch-all is gone, Slack is the only alert path
        golden = GOLDEN_SLACK1.read_text()
        page_route = golden.index('receiver: capsule-slack-alerts', golden.index("routes:"))
        severity_page = golden.index('"page"]', page_route)
        self.assertLess(page_route, severity_page)
        self.assertNotIn("telegram", golden.lower())
        self.assertNotIn("telegram", _render(POLICY_TEMPLATE).lower())   # the live render
        self.assertIn("severity: notice", _rule_block("unowned-work-idle"))   # row 623


class NoPrivateBoardInRules(unittest.TestCase):
    """rules.yaml is a static, public file: no board name is hard-wired into it. The dead-man
    watched set comes only from each board's latest heartbeat `watch` flag."""

    def test_rules_name_no_private_board(self):
        if not DENYLIST.is_file():
            self.skipTest("release/private-denylist.txt is absent (public checkout): "
                          "no private names to check")
        spec = importlib.util.spec_from_file_location(
            "public_lint_for_rules_test", paths.REPO / "maintenance" / "public_lint.py")
        lint = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = lint
        spec.loader.exec_module(lint)
        rules, _ = lint._load_denylist(DENYLIST)
        patterns = [rx for category, rx, _ in rules if category == "project"]
        self.assertTrue(patterns, "denylist has no project rule to check")
        text = RULES.read_text()
        for rx in patterns:
            self.assertIsNone(re.search(rx, text, re.I),
                              f"rules.yaml matches private pattern {rx!r}")

    def test_deadman_queries_select_boards_by_watch(self):
        tick = _rule_block("capsule-tick-deadman")
        self.assertIn("coalesce(payload->>'watch','true') as watch from events"
                      " where kind='tick_health'", tick)
        self.assertIn("w.watch='true'", tick)
        self.assertIn("select coalesce(max(coalesce(extract(epoch from now()-t.last)/60,"
                      " 100000)), 0) from", tick)   # no watched board -> 0, not NULL
        unowned = _rule_block("unowned-work-idle")
        self.assertIn("coalesce(h.payload->>'watch','true') = 'true'", unowned)


