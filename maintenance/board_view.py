"""board_view.py - Boards/Engineering.md is a build artifact."""
import datetime as _dt
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import board      # noqa: E402
import events     # noqa: E402
import vault_conf  # noqa: E402
import vault_git  # noqa: E402

# Row 84: the cap was a proxy for "recent". The window is the thing itself, so
# the file changes when a card ages out rather than when a 31st card arrives.
DONE_WINDOW_DAYS = 14
TITLE_CAP = 120

BANNER = "<!-- generated by capsule-corp; do not edit. Your work goes in Boards/Intake.md. -->"

# Emitted verbatim so the notes app's Kanban plugin still recognises the file (live copy:
# Boards/Engineering.md:187-190).
SETTINGS_BLOCK = (
    "%% kanban:settings\n"
    "```\n"
    '{"kanban-plugin":"board","list-collapse":[' + ",".join(["false"] * len(board.COLUMNS)) + "]}\n"
    "```\n"
    "%%"
)

_WS_RE = re.compile(r"\s+")
# A whole `<!-- ... -->` span collapses to one placeholder so a title cannot splice in a
# second join-key comment; any unterminated marker left over (title cut off mid-comment)
# is then stripped on its own below.
_COMMENT_RE = re.compile(r"<!--.*?-->")


def _safe_title(text):
    """A card title flattened to one line that cannot forge a field or a join key:
    whitespace collapsed, `**` and `~~` stripped (they are the renderer's own
    markers), ` · ` neutralised (it is the field separator) and any HTML comment (the
    join key's own delimiters) collapsed to one placeholder so it cannot forge a
    second `<!-- kanban:..."""
    t = _WS_RE.sub(" ", str(text or "")).strip()
    t = t.replace("**", "").replace("~~", "")
    t = _COMMENT_RE.sub("(comment)", t)
    t = t.replace("<!--", "(comment)").replace("-->", "").replace(" · ", " ")
    t = _WS_RE.sub(" ", t).strip()
    if len(t) > TITLE_CAP:
        t = t[:TITLE_CAP - 1].rstrip() + "…"
    return t or "(untitled)"


def done_at(card):
    """The epoch seconds a card finished, or None: the newest stamped run end."""
    stamps = [r.get("ended_at") for r in card.runs if r.get("ended_at") is not None]
    try:
        return max(float(s) for s in stamps) if stamps else None
    except (TypeError, ValueError):
        return None


def done_date(card):
    """The UTC calendar date a card finished, or None."""
    ts = done_at(card)
    if ts is None:
        return None
    return _dt.datetime.fromtimestamp(ts, tz=_dt.timezone.utc).date()


def in_done_window(card, *, today):
    """True when a done card still belongs on the board (row 84)."""
    d = done_date(card)
    if d is None:
        return False
    return (today - d).days <= DONE_WINDOW_DAYS


def card_line(card):
    """One card, one line. No indented body: the text lives in the spec note and (from
    2b) the ledger, and duplicating it here re-creates the thing this build deletes."""
    title = _safe_title(card.title)
    fields = [card.legacy_status or "?", card.board]
    if card.spec_slug:
        fields.append(f"[[Specs/{card.spec_slug}]]")
    fields.append(f"<!-- kanban:{card.board}/{card.id} -->")
    if card.legacy_status == "done":
        ts = done_at(card)
        head = f"- [x] ~~**{title}**~~"
        if ts is not None:
            # UTC, not the host's local zone.
            head += " ✅ " + _dt.datetime.fromtimestamp(ts, tz=_dt.timezone.utc).date().isoformat()
    else:
        head = f"- [ ] **{title}**"
    return head + " · " + " · ".join(fields)


def _sort_key(card):
    """Controller ruling 3: grouped by repo. Grouping is this key plus the
    `· <repo>` field on every line - never a `### <repo>` sub-heading, which
    the Kanban plugin would read as card body and corrupt the lane."""
    return (card.board, card.id)


def render_board(cards, *, today):
    """The whole file, trailing newline included. Pure: no IO, no clock -
    `today` is passed in and is the only date not derived from a card."""
    by_col = {h: [] for h in board.COLUMN_NAMES}
    for c in cards:
        heading = board.column_of(c)
        if heading is not None:
            by_col[heading].append(c)
    # Row 85: no `generated:` line. The file must change when a card changes
    # column or ages out of the window, and on no other day.
    out = ["---", "", "kanban-plugin: board", "", "---", "", BANNER, ""]
    done_heading = board.COLUMN_NAMES[-1]
    for heading in board.COLUMN_NAMES:
        out.append(heading)
        out.append("")   # the Kanban plugin's own layout: one blank line before a lane's first card
        col = by_col[heading]
        if heading == done_heading:
            # Newest first, one convention: every key ASCENDING with the timestamp
            # negated, so the board/id tie-break runs the same way as in every other
            # lane.
            col = sorted(col, key=lambda c: (-(done_at(c) or 0.0), c.board, c.id))
            live = [c for c in col if in_done_window(c, today=today)]
            hidden = len(col) - len(live)
            col = live
        else:
            col = sorted(col, key=_sort_key)
            hidden = 0
        out += [card_line(c) for c in col]
        if hidden:
            out.append(f"<!-- {hidden} older cards: see {ARCHIVE_REL} -->")
        out.append("")
    out.append(SETTINGS_BLOCK)
    return "\n".join(out) + "\n"


ARCHIVE_BANNER = ("<!-- generated by capsule-corp; do not edit. Every card currently in Done, "
                  "oldest included. Per-card history is in Ledger/. -->")
ARCHIVE_UNDATED = "## undated"


def _pr_url_in(card):
    """The newest GitHub PR url in one card's own body, latest_summary and comments, or
    ""."""
    found = ""
    for text in (card.body, card.latest_summary):
        m = board.PR_URL_RE.search(text or "")
        if m:
            found = m.group(0)
    for c in card.comments:
        m = board.PR_URL_RE.search(str(c.get("body") or ""))
        if m:
            found = m.group(0)
    return found


def _lead_descendant(card, by_id):
    """The (board, id)-resolved FINALIZE/lead card below `card`, or None."""
    for cid in card.children:
        child = by_id.get((card.board, cid))
        if child is None:
            continue
        if child.assignee == "lead":
            return child
        for gcid in child.children:
            grandchild = by_id.get((child.board, gcid))
            if grandchild is not None and grandchild.assignee == "lead":
                return grandchild
    return None


def pr_url(card, by_id=None):
    """The newest GitHub PR url for `card`, or ""."""
    found = _pr_url_in(card)
    if found or not by_id:
        return found
    lead = _lead_descendant(card, by_id)
    return _pr_url_in(lead) if lead is not None else ""


def archive_line(card, by_id=None):
    """One finished card, one line."""
    d = done_date(card)
    return (f"- {d.isoformat() if d is not None else '-'} · {card.board} · "
            f"**{_safe_title(card.title)}** · {pr_url(card, by_id) or '-'} · "
            f"<!-- kanban:{card.board}/{card.id} -->")


def render_archive(cards, *, today):
    """Every done card, newest first, grouped under `## YYYY-MM` by the month it
    finished."""
    # Every collected card, not just the done ones: a done IMPL card's FINALIZE
    # descendant is looked up through this map, and it must resolve even though `done`
    # below filters the render list down to done cards.
    by_id = {(c.board, c.id): c for c in cards}
    done = sorted((c for c in cards if c.legacy_status == "done"),
                  key=lambda c: (-(done_at(c) or 0.0), c.board, c.id))
    out = ["---", "", "type: archive", "", "---", "", ARCHIVE_BANNER, ""]
    group = None
    for c in done:
        d = done_date(c)
        key = f"## {d.isoformat()[:7]}" if d is not None else ARCHIVE_UNDATED
        if key != group:
            if group is not None:
                out.append("")
            out += [key, ""]
            group = key
        out.append(archive_line(c, by_id))
    return "\n".join(out) + "\n"


# The configured vault, or None (no board file is written then). board_bridge.VAULT is the same
# value, spelled again rather than imported so this module never pulls in board_bridge.
VAULT = vault_conf.vault()
BOARD_REL = "Boards/Engineering.md"
ARCHIVE_REL = "Boards/Archive.md"
BACKUP_REL = "Boards/Engineering.pre-generated.md"
INTAKE_REL = "Boards/Intake.md"
COLLECT_STATUSES = board.LIVE_STATUSES | {"done"}


def vault_root(vault=None):
    """The vault, or None when there is nothing to write to."""
    p = Path(vault) if vault else VAULT
    return p if p is not None and p.is_dir() else None


def _refuse_default_vault_under_test(vault):
    """Guard against the 2026-09-07 incident: a test that calls `write`, `regenerate` or
    `migrate` with no `vault=` reaches whatever `$OBSIDIAN_VAULT_PATH` happens to be
    (the real vault, when a test's own isolation is missing or gets bypassed by a
    mock)."""
    if vault is None and os.environ.get("AGENT_OPS_NO_SEND"):
        raise RuntimeError("refusing to touch the default vault under test: "
                            "pass vault= explicitly")


def enabled():
    """The build's one rollout flag (spec 8.2): `CAPSULE_BOARD_VIEW=0` runs the tick
    with the ledger and intake live and the board file still hand-written."""
    return str(os.environ.get("CAPSULE_BOARD_VIEW", "1")).strip().lower() \
        not in ("", "0", "false", "no", "off")


def collect(*, boards_dir=None, runner=None):
    """Every renderable card on every board, as full `board.Card`s."""
    out = []
    for name in board.board_names(boards_dir):
        b = board.open_board(name, runner=runner, boards_dir=boards_dir)
        try:
            refs = b.list(statuses=COLLECT_STATUSES)
        except Exception as exc:
            events.log("card", "board_view", f"list failed for board {name}: {exc}", board=name,
                       severity="warn", payload={"event": "board_view_list_failed"})
            continue
        for ref in refs:
            card = b.try_show(ref.id)
            if card is None:
                events.log("card", "board_view", f"show failed for {ref.id}", board=name, task_id=ref.id,
                           severity="warn", payload={"event": "board_view_show_failed"})
                continue
            if board.is_helper(card):
                continue
            out.append(card)
    return out


def write(text, *, vault=None, rel=BOARD_REL):
    """Write one generated board file. Returns its path, or None with no vault."""
    _refuse_default_vault_under_test(vault)
    root = vault_root(vault)
    if root is None:
        return None
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def regenerate(*, vault=None, boards_dir=None, runner=None, today=None, git_runner=None):
    """The tick's one board-file step: pull, render from the DB, write both generated
    files, push them in ONE commit."""
    if not enabled():
        return None
    _refuse_default_vault_under_test(vault)
    root = vault_root(vault)
    if root is None:
        return None
    vault_git.pull(root, runner=git_runner)
    # UTC, not the host zone - `done_date`, the Done window boundary and the
    # archive's month heading are all UTC, so a local `date.today()` here would move the
    # window a day for a few hours every evening and churn both files for no state
    # change.
    today = today or _dt.datetime.now(_dt.timezone.utc).date()
    cards = collect(boards_dir=boards_dir, runner=runner)
    path = write(render_board(cards, today=today), vault=root)
    write(render_archive(cards, today=today), vault=root, rel=ARCHIVE_REL)
    vault_git.push(root, [BOARD_REL, ARCHIVE_REL], "board: generated view", runner=git_runner)
    return path


MIGRATED_COMMENT_PREFIX = "migrated from the board file: "
_ANNOT_RE = re.compile(r"<!--\s*kanban:(t_[0-9a-fA-F]+)\s*-->")


def INTAKE_MIGRATED_HEADING(today):
    return f"## Backlog (migrated {today.isoformat()})"


def _card_blocks(text):
    """[(title_line, [indented lines]), ...] for every `- [` card in a hand-written
    board file, in file order."""
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        if not lines[i].lstrip().startswith("- ["):
            i += 1
            continue
        title, body = lines[i], []
        j = i + 1
        while j < len(lines):
            s = lines[j]
            if s.strip() == "" or s.lstrip().startswith("- [") or s.startswith("## ") or s.startswith("%%"):
                break
            if s[:1] not in ("\t", " "):
                break
            body.append(s)
            j += 1
        out.append((title, body))
        i = j
    return out


def _upsert_intake_section(text, heading, block):
    """Replace `heading`'s body with `block`, or append the section. Replacing
    is what makes a second `migrate` a no-op."""
    lines = text.splitlines()
    try:
        start = lines.index(heading)
    except ValueError:
        head = text.rstrip("\n")
        return (head + "\n\n" if head else "") + heading + "\n" + "\n".join(block) + "\n"
    end = next((j for j in range(start + 1, len(lines)) if lines[j].startswith("## ")), len(lines))
    return "\n".join(lines[:start + 1] + list(block) + lines[end:]).rstrip("\n") + "\n"


INTAKE_TEMPLATE = (
    "---\n"
    "type: intake\n"
    "---\n"
    "<!-- Your file. One instruction per line. The bridge reads it every 10 minutes and clears\n"
    "     what it processed. Anything under the Notes heading is never touched. -->\n"
    "## New work\n"
    "## Approvals\n"
    "<!-- ## Findings is written by the nightly security job and the monthly agent review.\n"
    "     Nothing consumes it: a finding becomes a card only when you move its line up\n"
    "     under ## New work. -->\n"
    "## Findings\n"
    "## Notes\n"
)


def migrate(*, vault=None, boards_dir=None, runner=None, today=None, git_runner=None):
    """Run once, by hand, with the owner watching (spec 8.3)."""
    _refuse_default_vault_under_test(vault)
    today = today or _dt.date.today()
    root = vault_root(vault)
    summary = {"annotated": 0, "orphans": [], "intake_lines": 0, "comments": 0, "backup": None}
    if root is None:
        return summary
    vault_git.pull(root, runner=git_runner)
    src = root / BOARD_REL
    if not src.exists():
        return summary
    backup = root / BACKUP_REL
    if not backup.exists():
        backup.write_bytes(src.read_bytes())
    summary["backup"] = backup

    # Parse the pristine hand-written copy, never `src` directly: after the first run
    # `src` (Boards/Engineering.md) has already been overwritten with generated content,
    # and re-parsing that on a second run would feed the wrong lines into Intake and
    # break idempotency.
    intake_block = []
    for title, body in _card_blocks(backup.read_text(encoding="utf-8")):
        m = _ANNOT_RE.search(title)
        if not m:
            intake_block += [title.rstrip()] + [b.rstrip() for b in body]
            continue
        tid = m.group(1)
        summary["annotated"] += 1
        found = board.find_card(tid, boards_dir=boards_dir, runner=runner)
        if found is None:
            summary["orphans"].append((tid, title.strip()))
            continue
        b, card = found
        prose = " ".join(x.strip() for x in body if x.strip())
        if not prose:
            continue
        if prose in card.body or any(str(c.get("body") or "").startswith(MIGRATED_COMMENT_PREFIX)
                                     for c in card.comments):
            continue
        try:
            b.comment(tid, MIGRATED_COMMENT_PREFIX + prose)
            summary["comments"] += 1
        except Exception as exc:
            print(f"board_view.migrate: comment on {tid} failed: {exc}", file=sys.stderr)

    intake = root / INTAKE_REL
    text = intake.read_text(encoding="utf-8") if intake.exists() else INTAKE_TEMPLATE
    intake.write_text(_upsert_intake_section(text, INTAKE_MIGRATED_HEADING(today), intake_block),
                      encoding="utf-8")
    summary["intake_lines"] = len(intake_block)

    write(render_board(collect(boards_dir=boards_dir, runner=runner), today=today), vault=root)
    vault_git.push(root, [INTAKE_REL, BOARD_REL], "board: generated view (migration)", runner=git_runner)
    return summary


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(prog="board_view.py")
    sub = ap.add_subparsers(dest="cmd", required=True)
    render_p = sub.add_parser(
        "render", help="regenerate Boards/Engineering.md and Boards/Archive.md now")
    render_p.add_argument("--vault", required=True,
                          help="vault root, e.g. $OBSIDIAN_VAULT_PATH (required: no implicit default)")
    migrate_p = sub.add_parser("migrate", help="one-time: back up the hand-written board and generate it")
    migrate_p.add_argument("--vault", required=True,
                           help="vault root, e.g. $OBSIDIAN_VAULT_PATH (required: no implicit default)")
    ns = ap.parse_args(argv)
    print(f"vault: {ns.vault}")
    if ns.cmd == "render":
        p = regenerate(vault=ns.vault)
        print(p if p is not None else "no vault: nothing written")
        return 0
    s = migrate(vault=ns.vault)
    print(f"backup: {s['backup']}")
    print(f"annotated cards: {s['annotated']} (comments written: {s['comments']})")
    print(f"lines moved to Intake: {s['intake_lines']}")
    for tid, line in s["orphans"]:
        print(f"  ORPHAN (kept in the backup, on no board): {tid} {line[:80]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
