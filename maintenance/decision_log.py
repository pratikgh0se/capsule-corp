"""The decision log, machine-readable (Capsule decision row 128, M070).

Why now rather than at 300 rows: the log's parse window closes on SIZE, not on
count. All 123 rows are uniformly formed five-cell pipe rows today; at ~29
rows/day the table is 300 rows inside two weeks and the parser is far cheaper
to write against a clean table than a dirty one. The index note and the
per-domain views the study also asked for waited for the 300-row trigger
(row 128); that is long past, so they now live here too (M070), generated by
the same `sidecar` verb.

The invariant it protects (study §3.3): ONE TABLE IS THE AUTHORITY. The sidecar
is derived, machine-written, never hand-edited, and regenerated by the nightly
job. If the sidecar and the table disagree, the table wins and the sidecar is
stale - so `write_sidecar` is a pure function of the note's current bytes.

Numbers are append-only and never reused: the row number is the citation
handle, and `lint()` is what enforces it (row 128, M069).

stdlib only. No MCP, no vault write tools, no network.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from capsule import host, legacy_names, safe_write  # noqa: E402

SIDECAR_NAME = "decisions.jsonl"
# A row is `| <int> | ... | <status> |`. Anchored on the leading pipe and a
# bare integer so the preamble's prose pipes, the header row (`| # |`) and the
# separator (`|---|`) are all excluded by construction rather than by a
# blacklist that a new section heading could slip past.
_ROW_RE = re.compile(r"^\|\s*(\d+)\s*\|(.+)\|\s*$")
_DATE_RE = re.compile(r"\b(\d{4}-\d{2}-\d{2})\b")
# A trailing parenthetical on the Topic cell is provenance ("(the owner,
# 2026-09-09 21:05)"), not the topic. Stripped from `title`, kept in `date`.
_TRAILING_PAREN_RE = re.compile(r"\s*\([^()]*\)\s*$")
# Split on a pipe only when it is not itself escaped (`\|`), so a cell such as
# `<R1\|R2\|R3>` (row 131) stays one cell instead of being torn apart.
_CELL_SPLIT_RE = re.compile(r"(?<!\\)\|")
_KEYS = ("number", "title", "date", "text", "status")


def _unescape_cell(cell):
    """`\\|` -> `|` after the cell boundary has already been decided."""
    return cell.replace("\\|", "|")


def parse(text):
    """EVERY row from the authority table, in FILE ORDER.

    Deliberately NOT keyed by number: a dict keyed on the
    row number collapsed two rows numbered 128 into one - last writer wins -
    before `lint()` could ever see the duplicate, so M069's headline rule
    ("numbers are append-only and never reused") was unenforceable through the
    only code path that runs it, and the losing row dropped out of the sidecar
    that now feeds worker cards. Multiplicity and file order are the two
    things the lint needs, so parse() preserves both and the two consumers
    resolve them: `lint()` names duplicates, `render_jsonl()` keeps the FIRST
    occurrence and sorts for output.

    A malformed row is SKIPPED, never fatal: one bad row must not empty the
    sidecar and take every citation with it. `lint()` is what names them.
    """
    rows = []
    for line in (text or "").splitlines():
        m = _ROW_RE.match(line.strip())
        if not m:
            continue
        cells = [_unescape_cell(c.strip()) for c in _CELL_SPLIT_RE.split(m.group(2))]
        if len(cells) < 2:
            continue
        topic, status = cells[0], cells[-1]
        body = " ".join(c for c in cells[1:-1] if c).strip()
        if len(cells) == 2:  # `| n | date | text |`: rows 595-604 have no status cell
            body, status = cells[1], None
        if not topic and not body:
            continue
        m_date = _DATE_RE.search(topic) or _DATE_RE.search(body)
        rows.append({
            "number": int(m.group(1)),
            "topic": topic,  # raw cell, provenance kept; not in `_KEYS`, so not in the sidecar
            "title": _TRAILING_PAREN_RE.sub("", topic).strip(),
            "date": m_date.group(1) if m_date else None,
            "text": body,
            "status": status or None,
        })
    return rows


def lint(rows):
    """Problems with the log's numbering, one human-readable line each.

    Three rules, all cheap, all about ONE property: the row number is the
    citation handle. ~30 citations across Knowledge/, docs/PROGRESS.md and the
    specs are bare row numbers, so a reused or renumbered row silently
    repoints every one of them. Row 119 (renumbered from a duplicate "row 23"
    on 2026-09-09) is the precedent and was the last cheap moment to write this
    down.

    - NO DUPLICATES (warn): two rows may never carry the same number. The
      message names BOTH occurrences by their title, because the operator's
      next move is deciding which one keeps the number.
    - STARTS AT 1 (warn).
    - GAPS (info): a hole is reported, not hidden - but the
      real log has a genuine one from row 119's renumber, so a gap can never
      be a health ISSUE or the nightly note would carry the same warn forever
      and the duplicate signal would arrive pre-ignored. `info:`-prefixed
      lines are printed and never folded into vault health
      (vault_jobs.health).
    """
    problems = []
    if not rows:
        return ["the decision table has no parseable rows - the parser or the "
                "table's format has broken; every row citation is unresolvable"]
    seen = {}
    for r in rows:
        seen.setdefault(r["number"], []).append(r)
    for number, dupes in sorted(seen.items()):
        if len(dupes) > 1:
            named = " vs ".join(f"{(d.get('title') or d.get('text') or '?')!r}" for d in dupes)
            problems.append(f"duplicate row number {number} ({len(dupes)} rows share it: "
                            f"{named}) - numbers are append-only and never reused; the "
                            f"sidecar keeps the first occurrence only")
    numbers = sorted(seen)
    missing = [n for n in range(numbers[0], numbers[-1] + 1) if n not in seen]
    if missing:
        shown = ", ".join(str(n) for n in missing[:12])
        more = f" (+{len(missing) - 12} more)" if len(missing) > 12 else ""
        problems.append(f"info: gap in row numbers: {shown}{more} - a hole is fine if it "
                        f"was a decision (see row 119's renumber note); it is a bug if it "
                        f"was an accident")
    if numbers[0] != 1:
        problems.append(f"the table starts at row {numbers[0]}, not 1")
    return problems


def is_info(problem):
    """True for a lint line that is informational only - printed, counted in
    no health issue, never a non-zero exit."""
    return str(problem).startswith("info:")


def render_jsonl(rows):
    """One compact JSON object per line, number ascending, byte-stable.

    A duplicated number keeps its FIRST occurrence in file order: the table is read
    top-down, so the first row is
    the one the number was minted for and the later one is the mistake. `lint()` names
    both, so the loss is never silent.

    The emitted key order is `_KEYS`, in that order - part of the sidecar's
    byte contract. `Decisions/decisions.jsonl` is read by `cited_rows`/
    `push_block` and, once committed, its own commit time becomes the
    envelope stamp those pushes carry - so reordering `_KEYS` rewrites every
    line of that file and must be a deliberate change with its own commit,
    not a drive-by rename.
    """
    first = {}
    for r in rows:
        first.setdefault(r["number"], r)
    out = []
    for n in sorted(first):
        out.append(json.dumps({k: first[n].get(k) for k in _KEYS},
                              ensure_ascii=False, separators=(",", ":")))
    return "\n".join(out) + ("\n" if out else "")


# --- index and per-domain views (study §3.3 items 3 and 4, row 128, M070) ---
# Both are DERIVED from the table, never hand-edited, and written by the same
# `sidecar` verb as decisions.jsonl. The row number stays the citation handle:
# every view line starts with it, and `_check_views` fails a number the table
# no longer has.
# Names are collision-proof on purpose: a bare `views/<project>.md` or
# `Decisions/index.md` would shadow `Projects/<Project>.md` and the vault-root
# `index.md` in wikilink resolution. Study §3.3 item 5 (amendment provenance,
# the struck-through amended rows) is NOT built: it needs sidecar fields, and
# the sidecar's byte contract (see render_jsonl) changes only deliberately.
INDEX_NAME = "Decision index.md"
VIEWS_DIR = "views"
VIEW_PREFIX = "Decisions - "
_AUTH = "the authority is the decisions table"
_GEN_FM = "generated: decision_log.py"  # frontmatter line that marks a file as ours
_CLUSTER_RE = re.compile(r"^C(\d+)\b")
# First match wins, on the TITLE only. The titles are free prose, so this is a
# coarse, deterministic bucket and not a taxonomy: a wrong bucket costs a row
# showing up in a neighbouring view, never a wrong citation. Adding a rule
# moves rows between views on the next regeneration; the table is unaffected.
_DOMAIN_RULES = (
    ("themes", re.compile(r"^theme\b", re.I)),
    ("board", re.compile(r"\b(board|kanban|cards?)\b", re.I)),
    ("messaging", re.compile(rf"\b(slack|telegram|{legacy_names.CLASSIFIER_WORD}|notif\w*)\b",
                             re.I)),
    ("secrets", re.compile(r"\b(secrets?|credentials?|tokens?)\b", re.I)),
    ("ui", re.compile(r"\b(screens?|dashboards?|lookout|widgets?|ui)\b", re.I)),
    ("budget", re.compile(r"\b(budgets?|usage|weekly|limits?|cost)\b", re.I)),
    ("pipeline", re.compile(r"\b(spec|epic|merge|review|gate|tick|build)\b", re.I)),
)


def domain_of(row):
    """The view a row belongs to (also its index tag and its view file stem):
    its leading `C<n>` cluster tag, else the first keyword rule its title
    matches. The unmatched rest is over half the real log, so it is sharded by
    row-number block of 100 (`general-001-100`): a block is stable once full,
    so the nightly rewrites only the newest shard, not one ever-growing file."""
    title = row.get("title") or ""
    m = _CLUSTER_RE.match(title)
    if m:
        return f"c{m.group(1)}"
    for name, rx in _DOMAIN_RULES:
        if rx.search(title):
            return name
    lo = (row["number"] - 1) // 100 * 100 + 1
    return f"general-{lo:03d}-{lo + 99:03d}"


def _ordered(rows):
    """Number ascending, file order within a duplicated number (sorted is
    stable). Duplicates are kept: a hidden duplicate is the bug lint names."""
    return sorted(rows, key=lambda r: r["number"])


def _frontmatter(kind, source, domain=None):
    lines = ["---", "type: generated-view", _GEN_FM, f"kind: {kind}"]
    if domain:
        lines.append(f"domain: {domain}")
    if source:
        lines.append(f"authority: \"[[{source}]]\"")
    return "\n".join(lines + ["---"])


def _preamble(kind, what):
    return (f"## For future agent\n\nThis note is a generated {kind}; {_AUTH}. Never edit it; "
            f"regenerate it with `decision_log.py sidecar`. {what} Cite a row by its number and "
            f"resolve it in the authority table.\n")


def _render_index(rows, source=None):
    """One line per row: `- <number> | <title> | <status> | #<domain>`.
    Byte-stable: a pure function of the rows, no clock."""
    out = [_frontmatter("index", source), "", "# Decision index", "",
           f"> generated index; {_AUTH}.", "",
           _preamble("index", "One line per table row (number, title, status, domain tag)."),
           "## Views", ""]
    out += [f"- [[{VIEW_PREFIX}{d}]]" for d in sorted({domain_of(r) for r in rows})]
    out += ["", "## Rows", ""]
    for r in _ordered(rows):
        title, status = r["title"] or "-", r.get("status") or "-"
        out.append(f"- {r['number']} | {title} | {status} | #{domain_of(r)}")
    return "\n".join(out) + "\n"


def _render_views(rows, source=None):
    """{view name: note text}, one note per view, rows in number order."""
    by_domain = {}
    for r in _ordered(rows):
        by_domain.setdefault(domain_of(r), []).append(r)
    views = {}
    for domain in sorted(by_domain):
        out = [_frontmatter("view", source, domain), "", f"# Decisions: {domain}", "",
               f"> generated view; {_AUTH}.", "",
               _preamble("view", f"Rows filed under `{domain}` by their title."), ""]
        for r in by_domain[domain]:
            out.append(f"### {r['number']} - {r['title'] or '-'}")
            date = f" | date: {r['date']}" if r.get("date") else ""
            out.append(f"status: {r.get('status') or '-'}{date}")
            out.append("")
            out.append(r["text"] or "-")
            out.append("")
        views[domain] = "\n".join(out).rstrip("\n") + "\n"
    return views


def _put(out, path, body):
    """Write one generated file. A file already there that does not carry the
    generated marker is somebody's note: say so and leave it alone."""
    if path.is_file():
        try:
            current = path.read_text(encoding="utf-8")
        except (OSError, ValueError):
            current = None
        if current == body:
            return False
        if current is None or _GEN_FM not in current[:300]:
            print(f"decision_log: {path} exists and is not generated; not overwriting",
                  file=sys.stderr)
            return False
    safe_write.atomic_write(out, path, body, create_dirs=True)
    return True


def _view_files(out):
    return sorted((Path(out) / VIEWS_DIR).glob(f"{VIEW_PREFIX}*.md"))


def _write_index_and_views(out, rows, source=None):
    """Regenerate `<out>/Decision index.md` and `<out>/views/Decisions - <domain>.md`.
    True when any byte changed. A generated view whose domain no longer exists
    is removed (it would otherwise keep rows the table has since lost); a file
    in views/ that is not ours is never touched."""
    out = Path(out)
    changed = _put(out, out / INDEX_NAME, _render_index(rows, source))
    views = _render_views(rows, source)
    for domain, body in views.items():
        changed |= _put(out, out / VIEWS_DIR / f"{VIEW_PREFIX}{domain}.md", body)
    for stale in _view_files(out):
        if stale.stem[len(VIEW_PREFIX):] in views or stale.is_symlink():
            continue
        try:
            ours = _GEN_FM in stale.read_text(encoding="utf-8")[:300]
        except (OSError, ValueError):
            continue
        if ours:
            stale.unlink()
            changed = True
    return changed


_VIEW_ROW_RE = re.compile(r"^### (\d+) ", re.M)
_INDEX_ROW_RE = re.compile(r"^- (\d+) \|", re.M)


def _check_views(rows, out):
    """Problems where a generated file names a row number the table lacks.
    Absent output is not a problem (nothing generated yet)."""
    have = {r["number"] for r in rows}
    out = Path(out)
    problems = []
    targets = [(out / INDEX_NAME, _INDEX_ROW_RE, "index")]
    targets += [(p, _VIEW_ROW_RE, f"view {p.stem}") for p in _view_files(out) if not p.is_symlink()]
    for path, rx, label in targets:
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, ValueError):
            continue
        if _GEN_FM not in text[:300]:
            continue
        gone = sorted({int(n) for n in rx.findall(text)} - have)
        if gone:
            shown = ", ".join(map(str, gone[:12]))
            problems.append(f"{label} names row(s) {shown} the table does not have "
                            f"- stale; rerun `decision_log.py sidecar`")
    return problems


def find_log(vault):
    """The single authority note under Decisions/ - the newest top-level note matching
    host.json `vault.decision_notes` (a glob under the vault). None when there is no vault or no
    match. A per-board DECISION note (Decisions/<board>/*.md, written by decisions.py) is NOT
    the table."""
    if not vault:
        return None
    note = Path(vault) / host.decision_note(vault)
    return note if note.is_file() else None


def write_sidecar(vault, log_path=None):
    """Regenerate `Decisions/decisions.jsonl`. True when bytes changed.

    Identical input, identical bytes, no write: the sidecar sits in the vault's
    git repo and a daily no-op commit is noise.
    """
    vault = Path(vault)
    log_path = Path(log_path) if log_path else find_log(vault)
    if not log_path or not log_path.is_file():
        return False
    body = render_jsonl(parse(log_path.read_text(encoding="utf-8")))
    out = vault / "Decisions" / SIDECAR_NAME
    if out.is_file() and out.read_text(encoding="utf-8") == body:
        return False
    safe_write.atomic_write(vault, out, body, create_dirs=True)
    return True


def load_sidecar(vault):
    """{number: row} from the sidecar, or {} when it is absent or unreadable.
    Callers degrade to "no rows pushed", never to a wedge (design §9)."""
    path = Path(vault) / "Decisions" / SIDECAR_NAME
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, ValueError):
        return {}
    out = {}
    for line in lines:
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except ValueError:
            continue
        if isinstance(row.get("number"), int):
            out[row["number"]] = row
    return out


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    cmd = argv[0] if argv else ""
    vault = argv[1] if len(argv) > 1 else None
    if not vault:
        vault = host.vault_path()
    if not vault:
        print("decision_log: no vault configured (vault.path); nothing to do",
              file=sys.stderr)
        return 0
    out = Path(vault) / "Decisions"
    if cmd == "sidecar":
        changed = write_sidecar(vault)
        print(f"decisions.jsonl: {'rewritten' if changed else 'unchanged'}")
        log = find_log(vault)
        if log:
            rows = parse(log.read_text(encoding="utf-8"))
            changed = _write_index_and_views(out, rows, source=log.stem)
            print(f"index and views: {'rewritten' if changed else 'unchanged'}")
        return 0
    if cmd == "lint":
        log = find_log(vault)
        if not log:
            print("no decision-log note found under Decisions/", file=sys.stderr)
            return 2
        rows = parse(log.read_text(encoding="utf-8"))
        problems = lint(rows) + _check_views(rows, out)
        for p in problems:
            print(p)
        real = [p for p in problems if not is_info(p)]
        print(f"decision-log lint: {len(real)} problem(s)"
              + (f", {len(problems) - len(real)} informational" if len(real) != len(problems) else ""))
        return 1 if real else 0
    print("usage: decision_log.py <sidecar|lint> <vault>", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
