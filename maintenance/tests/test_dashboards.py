# `name = 'x'` and `name in ('a','b')` - the second form was invisible to the
# original single-literal pattern, so a typo inside an `in (...)` list slipped
# past this suite (review I3).
_NAME_EQ_RE = re.compile(r"name\s*=\s*'([^']+)'")
_NAME_IN_RE = re.compile(r"name\s+in\s*\(([^)]*)\)", re.I)
_IN_LIT_RE = re.compile(r"'([^']+)'")

# A latest-value panel: `distinct on` or `limit 1` over `samples`. Every one of
# them must be bounded, or a dead probe leaves a stale number on screen forever
# instead of an empty panel (review I3).
LATEST_RE = re.compile(r"distinct on|limit\s+1", re.I)
TS_BOUND = "ts > now() - interval '30 minutes'"


def sample_names(sql):
    names = list(_NAME_EQ_RE.findall(sql))
    for group in _NAME_IN_RE.findall(sql):
        names.extend(_IN_LIT_RE.findall(group))
    return names


def panel_sqls(*dashes):
    for dash in dashes:
        for panel in dash["panels"]:
            for target in panel.get("targets", []):
                yield dash, panel, target.get("rawSql", "")


class Regeneration(unittest.TestCase):
    """The committed dashboards/*.json must be exactly what the generator
    produces right now - no hand-edits, no drift."""

    def test_regenerate_matches_committed_json(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = build_dashboards.write_all(out_dir=tmp)
            committed_dir = build_dashboards.PLUMBING
            # Only plumbing/ is compared: `dashboards/lookout/` is regenerated by build_lookout.py
            # and checked by its own golden test (maintenance/tests/test_build_lookout.py).
            committed = {p.name for p in committed_dir.glob("*.json")}
            generated = {p.name for p in (Path(out) / "plumbing").glob("*.json")}
            self.assertEqual(committed, generated)
            for name in committed:
                want = (committed_dir / name).read_bytes()
                got = (Path(out) / "plumbing" / name).read_bytes()
                self.assertEqual(got, want, f"{name} differs from the generator's output")


class NewDashboards(unittest.TestCase):
    def setUp(self):
        self.postgres = json.loads(
            (build_dashboards.PLUMBING / "capsule-postgres.json").read_text())
        self.boards = json.loads(
            (build_dashboards.PLUMBING / "capsule-boards.json").read_text())
        self.second_brain = json.loads(
            (build_dashboards.PLUMBING / "vault.json").read_text())

    def test_files_exist_with_expected_uids(self):
        self.assertEqual(self.postgres["uid"], "ops-capsule-postgres")
        self.assertEqual(self.boards["uid"], "ops-capsule-boards")

    def test_panel_1_is_the_question_text_panel(self):
        p = self.postgres["panels"][0]
        self.assertEqual(p["type"], "text")
        self.assertEqual(p["title"], "Is the events store healthy?")

        b = self.boards["panels"][0]
        self.assertEqual(b["type"], "text")
        self.assertEqual(b["title"], "Are the boards moving?")

    def test_every_name_literal_is_a_known_names_key(self):
        for dash, panel, sql in panel_sqls(self.postgres, self.boards):
            for name in sample_names(sql):
                self.assertIn(name, obs_probe.NAMES,
                              f"{name!r} in {dash['uid']} panel "
                              f"{panel['title']!r} is not a NAMES key")

    def test_name_in_lists_are_seen_by_the_extractor(self):
        """The extractor itself, not a dashboard: `name in ('a','b')` must
        yield both literals (an `in (...)` list used to be invisible)."""
        self.assertEqual(
            sample_names("select 1 from samples where name in ('capsule.host.load1',"
                          " 'capsule.host.disk.pct')"),
            ["capsule.host.load1", "capsule.host.disk.pct"])
        self.assertEqual(sample_names("where name='capsule.host.load1'"),
                          ["capsule.host.load1"])

    def test_every_latest_value_samples_panel_is_time_bounded(self):
        checked = 0
        for dash, panel, sql in panel_sqls(self.postgres, self.boards):
            if "from samples" not in sql or not LATEST_RE.search(sql):
                continue
            checked += 1
            self.assertIn(TS_BOUND, sql,
                          f"{dash['uid']} panel {panel['title']!r} reads the latest "
                          "sample without a ts bound - a dead probe would leave a "
                          "stale value on screen")
        self.assertGreaterEqual(checked, 13, "expected every latest-value panel to be seen")

    def test_probe_age_stat_on_both_new_dashboards(self):
        for dash in (self.postgres, self.boards):
            panel = next((p for p in dash["panels"] if p["title"] == "Probe age"), None)
            self.assertIsNotNone(panel, f"{dash['uid']} has no Probe age stat")
            self.assertEqual(panel["type"], "stat")
            sql = panel["targets"][0]["rawSql"]
            self.assertIn("capsule.job.age_s", sql)
            self.assertIn("labels->>'job' = 'obs-probe'", sql)
            steps = panel["fieldConfig"]["defaults"]["thresholds"]["steps"]
            self.assertIn(("red", 1200), [(s["color"], s["value"]) for s in steps])
            self.assertEqual(panel["fieldConfig"]["defaults"]["unit"], "s")

    def test_links_bar_includes_both_new_dashboards_both_ways(self):
        for dash, other in ((self.boards, "ops-capsule-postgres"),
                            (self.postgres, "ops-capsule-boards")):
            uids = {l["url"].split("/d/")[1] for l in dash["links"]}
            self.assertIn(other, uids)

    def test_no_live_dashboard_links_outside_the_live_set(self):
        live = {u for _, u in dash_lib.LEVEL1 + dash_lib.DRILL}
        for dash in (self.postgres, self.boards, self.second_brain):
            for link in dash["links"]:
                self.assertIn(link["url"].split("/d/")[1], live, dash["uid"])

    def test_row_titles_in_order(self):
        want = ["Is it up?", "Load", "Storage", "Logs"]
        for dash in (self.postgres, self.boards):
            rows = [p["title"] for p in dash["panels"] if p["type"] == "row"]
            self.assertEqual(rows, want, f"{dash['uid']} row order")

    def test_no_slo_row_statement_present(self):
        want = "SLOs: none for Capsule components yet (D-7 covers applications)."
        for dash in (self.postgres, self.boards):
            texts = [p for p in dash["panels"] if p["type"] == "text"]
            found = any(want in (p.get("content") or p["title"] or "")
                        for p in texts) or any(
                        want in json.dumps(p) for p in texts)
            self.assertTrue(found, f"{dash['uid']} is missing the no-SLO statement")


if __name__ == "__main__":
    unittest.main()
